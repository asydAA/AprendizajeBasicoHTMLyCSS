// Operadores Aritméticos

// Suma (+)

const suma = 5 + 3; // 8
console.log(suma);

// Resta (-)

const resta = 5 - 3; // 2
console.log(resta);

// Multiplicación (*)

const multiplicacion = 5 * 3; // 15
console.log(multiplicacion);

// división (/)

const division = 6 / 3; // 2
console.log(division);

// Módulo (%)

const modulo = 5 % 2; // 1
console.log(modulo);

// Exponeciación (**)

const potencia = 2 ** 3; //8
console.log(potencia);

// Operadores de Asignación

// Asignación con Suma (+=)
let a = 5;
a += 3;
console.log(a);

// Asignación con Resta (-=)

let b = 10;
b -= 4;
console.log(b);

// Asignación con Multiplicación (*=)

let c = 6;
c *= 2;
console.log(c);

// Asignación con división (/=)

let d = 15;
d /= 3;
console.log(d);

// Operadores de incremento y decremento

let contador = 10;

contador++; // Incremento en 1
console.log(contador);

contador--; // Decremento en 1
console.log(contador);

// Infinity -Infinity
console.log(1 / 0);
console.log(-1/0);

// NaN
console.log(0/0);
console.log('hola' * 2);